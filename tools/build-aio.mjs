#!/usr/bin/env node
// Builds AllInOne/plugin.js: every TJ-Plugins plugin (except the ones in SKIP) embedded in its own
// sandbox, plus the All-in-one layer in tools/aio/core.js that merges their home rows, searches and
// streams. Run from the repo root or tools/:  node tools/build-aio.mjs
// When the embedded code changed, AllInOne/plugin.json's version is bumped so the app offers the update.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "AllInOne");
const SKIP = new Set(["AllInOne", "ReelFren", "tools", "relay", "dist", "node_modules"]);

// home/search grouping of every plugin; plugins not listed default to "movies"
const GROUP = {
  "321MoviesUK": "movies", CineHD: "movies", CineJoy: "movies", Cinezo: "movies", Fmovies: "movies",
  HiCine: "movies", MoviesHubHD: "movies", NetMirror: "movies", RiveStream: "movies", ScreenScape: "movies",
  Vidbox: "movies",
  CineFreak: "hindi", KatMovieHD: "hindi", Movies4u: "hindi", SSRMovies: "hindi",
  DesiSerialOnline: "serial", DesiSerials: "serial",
  DesiDubAnime: "anime", PikaHD: "anime", RareAnimes: "anime", SubDubAnime: "anime",
  KatDrama: "drama", KDMaza: "drama",
};
// plugins with a TMDB catalog: clean titles, posters and cast, so preferred for the details page
const TMDB = new Set(["Cinezo", "ScreenScape", "CineHD", "CineJoy", "Fmovies", "RiveStream", "Vidbox", "321MoviesUK", "MoviesHubHD"]);

const dirs = fs.readdirSync(ROOT, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith(".") && !SKIP.has(d.name))
  .map((d) => d.name)
  .filter((d) => fs.existsSync(path.join(ROOT, d, "plugin.js")) && fs.existsSync(path.join(ROOT, d, "plugin.json")))
  .sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }));

let subs = "";
const hash = crypto.createHash("sha256");
for (const d of dirs) {
  const man = JSON.parse(fs.readFileSync(path.join(ROOT, d, "plugin.json"), "utf8"));
  let src = fs.readFileSync(path.join(ROOT, d, "plugin.js"), "utf8").replace(/^\uFEFF/, "");
  if (/\bimport\s+[\w{*]|\brequire\(/.test(src.split("\n").slice(0, 5).join("\n"))) throw new Error(d + ": modules are not supported");
  hash.update(d + "\0" + JSON.stringify(man) + "\0" + src + "\0");
  const meta = { id: d, name: man.name, version: man.version, group: GROUP[d] || "movies", tmdb: TMDB.has(d) };
  subs += `\n// ═════════════ ${man.name} v${man.version} (${d}/plugin.js) ═════════════\n` +
    `__AIO_SUBS.push({ meta: ${JSON.stringify(meta)}, manifest: ${JSON.stringify(Object.assign({}, man, { aio: true }))},\n` +
    `make: function (manifest, globalThis, getPreference, setPreference) {\n${src}\n} });\n`;
}
const core = fs.readFileSync(path.join(ROOT, "tools", "aio", "core.js"), "utf8");
hash.update(core);
const digest = hash.digest("hex").slice(0, 16);

const manPath = path.join(OUT_DIR, "plugin.json");
const outPath = path.join(OUT_DIR, "plugin.js");
const man = JSON.parse(fs.readFileSync(manPath, "utf8"));
const prev = fs.existsSync(outPath) ? (fs.readFileSync(outPath, "utf8").match(/aio-build: ([0-9a-f]+)/) || [])[1] : null;

const out = `// All-in-one by TJ-Plugins — GENERATED by tools/build-aio.mjs, do not edit by hand.\n` +
  `// Embeds: ${dirs.join(", ")}\n// aio-build: ${digest}\n` +
  `(function () {\nvar __AIO_SUBS = [];\n${subs}\n${core}\n})();\n`;

if (prev === digest) { console.log(`AllInOne: unchanged (v${man.version}, ${dirs.length} plugins)`); process.exit(0); }
fs.writeFileSync(outPath, out);
if (prev && !process.argv.includes("--no-bump")) {
  man.version = Number(man.version) + 1;
  fs.writeFileSync(manPath, JSON.stringify(man, null, 2) + "\n");
}
console.log(`AllInOne: built v${man.version} — ${dirs.length} plugins, ${(out.length / 1024).toFixed(0)} KB, build ${digest}`);
